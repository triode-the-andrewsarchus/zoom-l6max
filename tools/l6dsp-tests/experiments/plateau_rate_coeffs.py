#!/usr/bin/env python3
"""Generate or check the experimental 48/32 kHz Rust FIR phase tables."""

import argparse
from pathlib import Path

from plateau_rate import DOWN, UP

ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / "patches/dual-efx/src/plateau_rate_coeffs.rs"


def generate():
    lines = ["// Generated by tools/l6dsp-tests/experiments/plateau_rate_coeffs.py."]
    for name, table in (("DOWN", DOWN), ("UP", UP)):
        lines.append(f"pub(super) const {name}: [[f32; 64]; {len(table)}] = [")
        for row in table:
            lines.append("    [")
            for start in range(0, 64, 4):
                values = ", ".join(f"{float(x):.9e}f32" for x in row[start:start + 4])
                lines.append(f"        {values},")
            lines.append("    ],")
        lines.append("];\n")
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed tables differ")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if OUTPUT.read_text() != expected:
            raise SystemExit("generated coefficients differ")
    else:
        OUTPUT.write_text(expected)
